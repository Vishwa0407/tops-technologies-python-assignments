# 1. Create variables to store details of a Flipkart product: product_name, price, is_available, and rating. Print each variable and its data type using the type() function.

# Creating variables to store details of a Flipkart product

product_name = "Samsung Galaxy S21"
price = 69999.99
is_available = True
rating = 4.5

# Printing each variable and its data type

print("Product Name:", product_name, "Data Type:", type(product_name))
print("Price:", price, "Data Type:", type(price))
print("Is Available:", is_available, "Data Type:", type(is_available))
print("Rating:", rating, "Data Type:", type(rating))