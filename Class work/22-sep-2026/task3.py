# Year to Days
year = int(input("Enter Year : "))
print("Days Are: ", year * 365)

# Month to Years
month = int(input("Enter Month: "))
print("Years Are: ", month / 12)

# Years to Weeks
year_to_weeks = int(input("Enter Year for Weeks: "))
print("Weeks Are: ", year_to_weeks * 52)

# Days to Weeks
days = int(input("Enter Days: "))
print("Weeks Are: ", days / 7)

# Weeks to Months
weeks = int(input("Enter Weeks: "))
print("Months Are: ", weeks / 4)